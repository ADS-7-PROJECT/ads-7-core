/*
 * seal.h — نظام الأختام والثقة (Trust Chain / Seal System) — أول نسخة عاملة
 *
 * تطبيق مبسط لتصميم الأمس (المنطقة المحجوزة + الختم اللي لازم يمر قبل أي كتابة).
 *
 * ⚠️ تبسيط متعمد موثق بوضوح — الفرق عن التصميم الكامل بـ PROJECT.md:
 *   - التصميم الكامل: أختام غير متماثلة (asymmetric) لكل توزيعة (root + sub seals)
 *     بتسلسل هرمي كامل، شبه TUF.
 *   - هذي النسخة: ختم واحد متماثل (HMAC-SHA256) على مستوى المستودع كله —
 *     أبسط بكثير، بس يثبت **نفس المبدأ الجوهري**: "المنطقة المحجوزة ما
 *     تُكتب/تُعدَّل إلا لو معك الختم الصحيح". الترقية للتصميم الهرمي الكامل
 *     (مفاتيح غير متماثلة لكل توزيعة + Threshold Secret Sharing لحماية
 *     الختم الأساسي) نقطة مفتوحة موثقة، مؤجلة لمرحلة لاحقة.
 *
 * آلية العمل:
 *   1. ads7_seal_init ينشئ "الختم الأساسي" — سر عشوائي 32 بايت، يُخزن بملف
 *      محمي داخل المستودع (<repo>/.seal_root.key). هذا يمثل "مين يملك الختم".
 *   2. ads7_seal_protect يحسب HMAC-SHA256(seal_secret, محتوى الملف) ويخزنه
 *      كـ "الختم" بجانب المانيفست — الملف صار بالمنطقة المحجوزة.
 *   3. أي محاولة repo-pack لاحقة على نفس الاسم تتطلب معرفة الختم الصحيح
 *      (اشتقاق نفس HMAC) قبل ما تسمح بالكتابة فوقه — حتى لو المستخدم عنده
 *      صلاحيات كاملة على نظام الملفات نفسه (root)، بدون الختم الصحيح
 *      البرنامج نفسه يرفض.
 */

#ifndef ADS7_SEAL_H
#define ADS7_SEAL_H

/* ينشئ (أو يتحقق من وجود) الختم الأساسي لمستودع — لازم يُستدعى مرة وحدة
 * لكل مستودع قبل استخدام أي ميزة حماية. لو الختم موجود أصلاً، ما يسويه من جديد. */
int ads7_seal_init(const char *repo_dir);

/* يحط ملف/مانيفست ضمن "المنطقة المحجوزة" — يحسب ويخزن ختم HMAC له. */
int ads7_seal_protect(const char *repo_dir, const char *manifest_name);

/* يتحقق هل manifest_name محمي بختم صالح حالياً (يقارن الختم المخزن بإعادة
 * حساب HMAC على المحتوى الحالي) — يُستخدم قبل أي عملية كتابة. */
int ads7_seal_verify(const char *repo_dir, const char *manifest_name);

/* يفحص: هل هذا الاسم محمي أصلاً (عنده ملف .seal)؟ 1=نعم، 0=لا */
int ads7_seal_is_protected(const char *repo_dir, const char *manifest_name);

#endif
